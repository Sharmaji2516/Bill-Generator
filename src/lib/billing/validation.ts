import { z } from 'zod';

export const businessProfileSchema = z.object({
  id: z.string().min(2).max(40),
  tradeName: z.string().min(1).max(120),
  legalName: z.string().min(1).max(160),
  tagline: z.string().max(180).default(''),
  isParent: z.boolean().default(false),
  parentBusinessId: z.string().nullable().default(null),
  parentBusinessName: z.string().nullable().default(null),
  logoUrl: z.string().max(500).default('/images/chittortech_logo.png'),
  address: z.string().max(400).default(''),
  state: z.string().max(80).default('Rajasthan'),
  stateCode: z.string().max(10).default('08'),
  gstin: z.string().max(20).default(''),
  pan: z.string().max(15).default(''),
  udyamRegNo: z.string().max(40).default(''),
  email: z.string().max(160).default(''),
  phone: z.string().max(40).default(''),
  website: z.string().max(160).default(''),
  bankName: z.string().max(120).default(''),
  accountName: z.string().max(120).default(''),
  accountNumber: z.string().max(40).default(''),
  ifscCode: z.string().max(20).default(''),
  upiId: z.string().max(100).default(''),
  invoicePrefix: z.string().min(1).max(15),
  quotationPrefix: z.string().min(1).max(15),
  proformaPrefix: z.string().min(1).max(15),
  receiptPrefix: z.string().min(1).max(15),
  creditNotePrefix: z.string().min(1).max(15),
  debitNotePrefix: z.string().min(1).max(15),
  defaultTemplate: z.enum(['gst_tax', 'service_classic', 'modern', 'mewari', 'terms']),
  defaultGstRate: z.number().min(0).max(100),
  gstRegistered: z.boolean(),
  defaultCurrency: z.string().min(1).max(5).default('₹'),
  authorizedSignatory: z.string().max(120).default(''),
  paymentInstructions: z.string().max(600).default(''),
  defaultTerms: z.array(z.string().max(400)).default([]),
  invoiceFooter: z.string().max(240).default(''),
  complianceNote: z.string().max(600).default(''),
  accentColor: z.string().max(20).default('#2563EB'),
});

export const customerSchema = z.object({
  id: z.string().optional(),
  businessId: z.string().min(2).max(40),
  name: z.string().min(1, 'Customer name is required').max(140),
  companyName: z.string().max(160).default(''),
  email: z.string().max(160).default(''),
  phone: z.string().max(40).default(''),
  gstin: z.string().max(20).default(''),
  pan: z.string().max(15).default(''),
  address: z.string().max(400).default(''),
  state: z.string().max(80).default(''),
  stateCode: z.string().max(10).default(''),
  notes: z.string().max(600).default(''),
});

export const productSchema = z.object({
  id: z.string().optional(),
  businessId: z.string().min(2).max(40),
  name: z.string().min(1, 'Product or service name is required').max(160),
  description: z.string().max(500).default(''),
  itemType: z.enum(['service', 'product']).default('service'),
  hsnSac: z.string().max(20).default(''),
  unit: z.string().max(30).default('Units'),
  defaultWeight: z.string().max(40).optional(),
  price: z.number().min(0),
  gstRate: z.number().min(0).max(100),
  category: z.string().max(80).default('General'),
  active: z.boolean().default(true),
});

export const invoiceLineItemSchema = z.object({
  id: z.string().min(1),
  productId: z.string().optional(),
  description: z.string().min(1, 'Line item description is required').max(300),
  hsnSac: z.string().max(20).optional(),
  weight: z.string().max(40).optional(),
  unit: z.string().max(30).optional(),
  qty: z.number().min(0),
  rate: z.number().min(0),
  discountType: z.enum(['NONE', 'PERCENT', 'FIXED']).optional(),
  discountValue: z.number().min(0).optional(),
  gstRate: z.number().min(0).max(100).optional(),
  manualAmount: z.number().min(0).nullable().optional(),
});

export const gstConfigSchema = z.object({
  taxType: z.enum(['CGST_SGST', 'IGST', 'EXEMPT']),
  gstRate: z.number().min(0).max(100),
  placeOfSupply: z.string().max(100).default('Rajasthan'),
  placeOfSupplyCode: z.string().max(10).optional(),
  reverseCharge: z.boolean().default(false),
  primarySac: z.string().max(20).default(''),
  documentBadge: z.string().max(80).default('ORIGINAL FOR RECIPIENT'),
  serviceSummaryNote: z.string().max(300).default(''),
  enableRoundOff: z.boolean().default(false),
  invoiceDiscountType: z.enum(['NONE', 'PERCENT', 'FIXED']).default('NONE'),
  invoiceDiscountValue: z.number().min(0).default(0),
});

export const invoiceSaveSchema = z.object({
  id: z.string().optional(),
  businessId: z.string().min(2).max(40),
  documentType: z.enum([
    'TAX_INVOICE',
    'SERVICE_INVOICE',
    'QUOTATION',
    'PROFORMA_INVOICE',
    'PAYMENT_RECEIPT',
    'CREDIT_NOTE',
    'DEBIT_NOTE',
  ]),
  templateId: z.enum(['gst_tax', 'service_classic', 'modern', 'mewari', 'terms']),
  invoiceNumber: z.string().max(60).optional(),
  financialYear: z.string().max(15).optional(),
  issueDate: z.string().min(8).max(20),
  dueDate: z.string().max(20).default(''),
  status: z.enum(['DRAFT', 'UNPAID', 'PARTIAL', 'PAID', 'OVERDUE', 'CANCELLED']),
  currencySymbol: z.string().min(1).max(5).default('₹'),
  customer: z.object({
    customerId: z.string().optional(),
    name: z.string().min(1, 'Customer name is required').max(140),
    companyName: z.string().max(160).optional(),
    email: z.string().max(160).default(''),
    phone: z.string().max(40).default(''),
    address: z.string().max(400).default(''),
    gstin: z.string().max(20).default(''),
    pan: z.string().max(15).optional(),
    state: z.string().max(80).optional(),
    stateCode: z.string().max(10).optional(),
  }),
  gstConfig: gstConfigSchema,
  items: z.array(invoiceLineItemSchema).min(1, 'At least one line item is required'),
  paymentMethod: z.enum([
    'Bank Transfer',
    'UPI / PhonePe / GPay',
    'Cash',
    'Cheque',
    'Credit Card',
    'Other',
  ]),
  paymentInfo: z.string().max(800).default(''),
  terms: z.array(z.string().max(400)).default([]),
  notes: z.string().max(1000).default(''),
  amountPaid: z.number().min(0).optional(),
  digitalSeal: z
    .object({
      enabled: z.boolean(),
      statusText: z.string().max(40),
      style: z.enum(['teal', 'green', 'blue', 'charcoal', 'red']),
      verificationId: z.string().max(80),
      timestampText: z.string().max(80),
    })
    .optional(),
  editReason: z.string().max(300).optional(),
});

export const paymentRecordSchema = z.object({
  businessId: z.string().min(2).max(40),
  invoiceId: z.string().min(3).max(120),
  amount: z.number().positive('Payment amount must be greater than zero'),
  method: z.enum([
    'Bank Transfer',
    'UPI / PhonePe / GPay',
    'Cash',
    'Cheque',
    'Credit Card',
    'Other',
  ]),
  referenceNo: z.string().max(100).default(''),
  paymentDate: z.string().min(8).max(20),
  notes: z.string().max(400).default(''),
});

